// ---------------------------------------------------------------------------
// backend.js — the only file that talks to the ledger's server.
//
// The server is this app's own Cloudflare Worker + D1 (`worker/`): a generic
// store that keeps each session as an opaque JSON `payload`. Everything app.js
// sends or receives goes through the functions below.
//
// One sync PASSWORD gates it, with no email and no account. The password never
// leaves the browser: it is stretched with PBKDF2 into an "auth hash", and that
// hash is the bearer token. The server stores only SHA-256(token), so a dump of
// its table yields nothing replayable.
//
// No top-level side effects beyond reading localStorage, and no DOM — app.js
// owns the screens. Loaded after config.js (it reads API_URL) and before app.js.
// ---------------------------------------------------------------------------

const KDF_ITERATIONS = 650000;
const TOKEN_KEY = 'pl.syncToken';

// Kept in localStorage so the app does not ask for the password on every
// launch. "Lock" (signOut) removes it.
let syncToken = null;
try { syncToken = localStorage.getItem(TOKEN_KEY); } catch(e){ /* private mode */ }

function isSignedIn(){ return syncToken !== null; }

function setSyncToken(value){
  syncToken = value;
  try {
    if(value) localStorage.setItem(TOKEN_KEY, value);
    else localStorage.removeItem(TOKEN_KEY);
  } catch(e){ /* private mode: the token lives for this page load only */ }
}

function signOut(){ setSyncToken(null); }

// Carries the HTTP status so callers can tell "wrong password" (401) from
// "could not reach the server".
class BackendError extends Error {
  constructor(message, status){
    super(message);
    this.status = status;
  }
}

// ---------- Password → token ----------

function bytesToBase64(bytes){
  return btoa(String.fromCharCode(...bytes));
}

// A random 256-bit salt, generated by whichever device sets the password first.
function makeSalt(){
  return bytesToBase64(crypto.getRandomValues(new Uint8Array(32)));
}

// The salt and iteration count come from the server, so every device derives
// the same token from the same password.
async function deriveAuthHash(password, salt, iterations = KDF_ITERATIONS){
  const enc = new TextEncoder();
  const key = await crypto.subtle.importKey(
    'raw', enc.encode(password), 'PBKDF2', false, ['deriveBits']);
  const bits = await crypto.subtle.deriveBits(
    { name: 'PBKDF2', hash: 'SHA-256', salt: enc.encode(salt), iterations }, key, 256);
  return bytesToBase64(new Uint8Array(bits));
}

// ---------- HTTP ----------

async function backendCall(path, init = {}, auth = true){
  const headers = new Headers(init.headers);
  if(init.body) headers.set('content-type', 'application/json');
  if(auth){
    if(!syncToken) throw new BackendError('Not signed in', 401);
    headers.set('authorization', 'Bearer ' + syncToken);
  }
  // `no-store`: the ledger must never come out of the browser's HTTP cache.
  const res = await fetch(API_URL + path, { ...init, headers, cache: 'no-store' });
  if(!res.ok){
    // The Worker returns { error } and never quotes row data, so showing the
    // message is safe ("Wrong sync password", "Origin not allowed").
    const msg = await res.json().then(b => b && b.error).catch(() => null);
    throw new BackendError(msg || `Request failed (${res.status})`, res.status);
  }
  return res;
}

// ---------- Password / session ----------

// { salt, kdfIterations }, or null before anyone has set a password.
async function getSalt(){
  const res = await backendCall('/salt', {}, false);
  return res.json();
}

// Claim a brand-new ledger. The first password set wins, forever.
async function signup(password){
  const salt = makeSalt();
  const authHash = await deriveAuthHash(password, salt);
  await backendCall('/signup', { method: 'POST', body: JSON.stringify({ salt, authHash }) }, false);
  setSyncToken(authHash);
}

// Unlock an existing ledger. Throws BackendError(401) on a wrong password.
async function login(password){
  const info = await getSalt();
  if(!info) throw new BackendError('No ledger exists yet. Set a password to create one.', 404);
  const authHash = await deriveAuthHash(password, info.salt, info.kdfIterations);
  await backendCall('/login', { method: 'POST', body: JSON.stringify({ authHash }) }, false);
  setSyncToken(authHash);
}

// ---------- Records ----------

// Every record in `table`, tombstones included, as
// [{ id, payload, updatedAt, deletedAt }]. `payload` is a JSON string.
async function pullRecords(table){
  const res = await backendCall('/pull?table=' + encodeURIComponent(table));
  return res.json();
}

// Upsert one row. The row must carry `id`, `updatedAt` and `deletedAt`; the
// whole row travels as the payload. The server keeps whichever copy has the
// later `updatedAt`.
async function pushRecord(table, row){
  const records = [{
    id: row.id,
    payload: JSON.stringify(row),
    updatedAt: row.updatedAt,
    deletedAt: row.deletedAt || null
  }];
  await backendCall('/push', { method: 'POST', body: JSON.stringify({ table, records }) });
}
